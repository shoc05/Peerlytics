/** A lookup for one language: t('due', { date }) fills {date}. Unknown keys return the key. */
export function courseText(language = 'en') {
  const table = COURSE_STRINGS[language] || COURSE_STRINGS.en;
  return (key, vars) => {
    const text = table[key] ?? COURSE_STRINGS.en[key] ?? key;
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
  };
}
